<#
.SYNOPSIS
    Writes what the health dashboard shows in an environment (topology.json and the runtime diagrams) and delivers it:
    for a site in the cluster as a commit that Argo CD applies, for a site on Azure Static Web Apps as an upload
    (runtime aks-argocd).

.DESCRIPTION
    Step "Write dashboard content" of the Octopus project of a static site (<slug>-<name>, hosting "staticsite"), on
    the Kubernetes worker in the cluster, after "Update deployable"; octopus/projects.tf inlines this file. The site's
    image is the same in every environment; this step gives it the environment's content:
      1. Reads system.json on main and builds the topology (the dashboard's README has the contract): every
         environment, and in it every app with one node, the Deployment at its public address
         https://<slug>-<env>.<cluster.domain>, and where its pin is (the newTag of
         gitops/environments/<env>/<app>/kustomization.yaml). No Front Door, no standby: the runtime has neither.
      2. Renders one C4 deployment diagram per environment with PlantUML (the pinned version, checked by its SHA-256,
         its own layout engine): the subscription, the cluster's resource group, the cluster, the environment's
         namespace with the app, SQL Server and this site, and the browser. Every drawn element the page updates is
         checked in the SVG.
      3. Commits all of it as one ConfigMap, <name>-content, to gitops/environments/<env>/<name>/content.yaml through
         the GitHub API (scripts/github-token.ps1: the system's App or the stored token, never printed or passed as
         an argument). Argo CD applies the commit and the kubelet refreshes the files the site's web server reads;
         nothing restarts.
      4. Waits until the site serves the topology it wrote.
    The links into the Azure portal are conventions over system.json (the cluster, and with capability "telemetry" the
    environment's Application Insights); the portal asks the viewer to sign in. The manifest of a runtime diagram
    says where each box leads that topology.json has no link for (the subscription, the resource group, the cluster,
    the namespace, SQL Server, a static site, the browser: "links", see ConvertTo-ClusterDiagram).

    The same dashboard outside the cluster (hosting "staticwebapp": step "Update deployable" of its project, an Azure
    script on the hosted worker pool as the tier's deploy identity, so it runs while the cluster is stopped) gets 1 and
    2 the same way and then, instead of 3 and 4:
      3. Writes the files into the release's extracted package (package reference "site": the zip of the dashboard's
         release workflow) and uploads it to the Static Web App swa-<slug>-<env>-<name> that infra/cluster.bicep
         created, with the Static Web Apps CLI and the site's deployment token: read from Azure now, handed to the CLI
         through its environment, never stored.
      4. Waits until the site serves the topology it wrote, then records the site's address and the release in Git:
         gitops/environments/<env>/<name>/site.json. The address is generated by Azure; everything else that needs it
         (the other dashboard's diagram, the health report, the checks) reads that file.
    Both kinds of dashboard get the topology's "cluster" block: where the page reads the cluster's live status (the
    collector of gitops/platform/cluster-status.yaml) and Azure's facts about the AKS service (workflow
    cluster-status publishes them to branch "cluster-status").
#>
